const { chromium } = require("playwright");
const fs = require("fs");
const path = require("path");
const html = "<!doctype html><html><head><meta charset=utf8><meta name=viewport content=\"width=device-width,initial-scale=1,viewport-fit=cover\"></head><body>" + fs.readFileSync(path.join(__dirname, "demo-panitia-scanner.html"), "utf8") + "</body></html>";
const shots = path.join(__dirname, "shots"); fs.mkdirSync(shots, { recursive: true });
const ok = []; const check = (c, m) => { ok.push(!!c); console.log((c ? "✓ " : "✗ ") + m); };

(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 920 } });
  const errs = [];
  await ctx.route("https://demo.test/", (r) => r.fulfill({ contentType: "text/html", body: html }));
  await ctx.route("**/qrcode-generator/**", (r) => r.fulfill({ contentType: "text/javascript", path: require.resolve("qrcode-generator/qrcode.js") }));
  await ctx.route("**/jsqr@1.4.0/**", (r) => r.fulfill({ contentType: "text/javascript", path: path.join(__dirname, "../public/vendor/jsQR.js") }));
  await ctx.route("**/fonts.googleapis.com/**", (r) => r.fulfill({ contentType: "text/css", body: "" }));
  const p = await ctx.newPage();
  p.on("pageerror", (e) => errs.push(e.message));
  p.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
  await p.goto("https://demo.test/");
  const admin = p.frameLocator("#adminFrame"), scan = p.frameLocator("#scanFrame");
  await admin.locator(".tile").first().waitFor();
  check(await admin.locator("text=pendaftaran menunggu bayar").count(), "Admin terbuka di ringkasan");
  await scan.locator("#lgBtn").click();
  await scan.locator(".session").first().waitFor();
  check(/27 peserta lunas/.test(await scan.locator("#dataInfo").textContent()), "Scanner login & unduh data: " + await scan.locator("#dataInfo").textContent());
  await p.screenshot({ path: path.join(shots, "1-awal.png") });
  await scan.locator(".session", { hasText: "Seminar 1" }).click();
  await p.waitForTimeout(800);
  await p.locator(".mini").nth(1).click();
  await scan.locator("#result.ok").waitFor({ timeout: 8000 });
  check(true, "Kartu diarahkan ke kamera → hijau: " + await scan.locator("#rName").textContent());
  await p.screenshot({ path: path.join(shots, "2-scan-ok.png") });
  await p.waitForTimeout(2500);
  // offline
  await p.click("[data-net=offline]");
  await p.waitForTimeout(300);
  await p.locator(".mini").nth(2).click();
  await scan.locator("#result.ok").waitFor({ timeout: 8000 });
  check(true, "Tanpa sinyal tetap hijau: " + await scan.locator("#rName").textContent());
  await p.waitForTimeout(2200);
  await p.locator(".mini.wait").click();
  await scan.locator("#result.err").waitFor({ timeout: 8000 });
  check(true, "Peserta belum lunas → merah");
  await p.screenshot({ path: path.join(shots, "3-merah.png") });
  await p.waitForTimeout(2000);
  await scan.locator("#backBtn").click();
  await scan.locator("#pendingN").waitFor();
  const pend = await scan.locator("#pendingN").textContent();
  check(pend === "1", "1 scan menunggu terkirim (terbaca " + pend + ")");
  await p.click("[data-net=captive]");
  await scan.locator("#syncBtn").click();
  await scan.locator("#syncMsg:not([hidden])").waitFor();
  check(/login WiFi/.test(await scan.locator("#syncMsg").textContent()), "WiFi belum login terdeteksi");
  await p.screenshot({ path: path.join(shots, "4-captive.png") });
  await p.click("[data-net=online]");
  await scan.locator("#syncBtn").click();
  await p.waitForFunction(() => document.querySelector("#scanFrame").contentDocument.querySelector("#pendingN").textContent === "0", null, { timeout: 8000 });
  check(/diterima/.test(await p.locator("#logList").textContent()), "Sinkron masuk ke server (log)");
  await admin.locator("a[data-nav=kehadiran]").click();
  await admin.locator("text=Petugas Pintu 1").first().waitFor();
  check(true, "Admin melihat scan dari Petugas Pintu 1 di Kehadiran");
  await p.screenshot({ path: path.join(shots, "5-kehadiran.png") });
  // approve menunggu lalu scan lagi
  await admin.locator("a[data-nav=pendaftaran]").click();
  await admin.locator("[data-pay]").first().click();
  await admin.locator("[data-yes]").click();
  await admin.locator("#toast:has-text('Ditandai lunas')").waitFor();
  await scan.locator("#dlBtn").click();
  await scan.locator("#syncMsg:has-text('Data terbaru')").waitFor();
  check(true, "Admin approve → HP unduh ulang data: " + await scan.locator("#syncMsg").textContent());
  await admin.locator("a[data-nav=peserta]").click();
  await admin.locator("[data-qr]").first().click();
  await admin.locator(".qrbig img").waitFor();
  check(/^data:image/.test(await admin.locator(".qrbig img").getAttribute("src")), "QR tampil di admin");
  await admin.locator("[data-close]").first().click();
  await admin.locator("#printSel").click();
  await p.locator(".id").first().waitFor();
  check(await p.locator(".id").count() > 10, "Pratinjau cetak ID card: " + await p.locator(".id").count() + " kartu");
  await p.screenshot({ path: path.join(shots, "6-cetak.png") });
  await p.click("#ovClose");
  // mobile
  await p.setViewportSize({ width: 400, height: 860 });
  await p.waitForTimeout(300);
  await p.screenshot({ path: path.join(shots, "7-mobile.png") });
  console.log(errs.length ? "Errors:\n" + errs.join("\n") : "Tanpa error konsol");
  console.log(`${ok.filter(Boolean).length}/${ok.length}`);
  await b.close();
})();
